#!/usr/bin/env node
// Generates src/styles/tokens.css from src/styles/tokens.json and fails if a text pair in any
// theme is below its contrast minimum (WCAG 2.x relative luminance). Run: pnpm --filter web tokens
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const src = fileURLToPath(new URL('../src/styles/tokens.json', import.meta.url))
const out = fileURLToPath(new URL('../src/styles/tokens.css', import.meta.url))
const tokens = JSON.parse(readFileSync(src, 'utf8'))

const SELECTORS = {
  light: ':root',
  dark: ":root[data-theme='dark'],\n:root:not([data-theme]).prefers-dark",
  hc: ":root[data-theme='hc'],\n:root:not([data-theme]).prefers-hc",
}
const COLOR_SCHEME = { light: 'light', dark: 'dark', hc: 'dark' }

function luminance(hex) {
  const n = hex.replace('#', '')
  const channels = [0, 2, 4].map((i) => parseInt(n.slice(i, i + 2), 16) / 255)
  const [r, g, b] = channels.map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4))
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}

function ratio(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x)
  return (hi + 0.05) / (lo + 0.05)
}

function checkContrast() {
  const failures = []
  const report = []
  for (const [theme, values] of Object.entries(tokens.themes)) {
    for (const [fg, bg, min] of tokens.contrast.pairs) {
      const r = ratio(values[fg], values[bg])
      report.push(`${theme.padEnd(5)} ${fg.padEnd(14)} on ${bg.padEnd(15)} ${r.toFixed(2)}:1`)
      if (r < min) failures.push(`${theme}: ${fg} on ${bg} is ${r.toFixed(2)}:1, needs ${min}:1`)
    }
  }
  return { failures, report }
}

const decls = (entries, indent = '  ') =>
  entries.map(([k, v]) => `${indent}--${k}: ${v};`).join('\n')

function themeBlock(theme) {
  const values = Object.entries(tokens.themes[theme])
  const extra = theme === 'light' ? Object.entries(tokens.base) : []
  const zero = theme === 'hc' ? tokens.motionZero.map((k) => [k, '0ms']) : []
  return `${SELECTORS[theme]} {\n  color-scheme: ${COLOR_SCHEME[theme]};\n${decls([...values, ...extra, ...zero])}\n}`
}

const { failures, report } = checkContrast()
if (process.argv.includes('--report')) console.log(report.join('\n'))
if (failures.length > 0) {
  console.error(`Contrast check failed:\n${failures.join('\n')}`)
  process.exit(1)
}

const css = `/* GENERATED by scripts/build-tokens.mjs from tokens.json. Do not edit by hand.
   One vocabulary, three themes. Light is the default.
   Semantic rule: measured = amber, inferred = teal, warning = vermilion (placement warnings only).
   Accents are never the only cue; shape, position and words carry the meaning too. */

${['light', 'dark', 'hc'].map(themeBlock).join('\n\n')}

@media (prefers-reduced-motion: reduce) {
  :root {
${decls(
  tokens.motionZero.map((k) => [k, '0ms']),
  '    ',
)}
  }
}
`
writeFileSync(out, css)
console.log(`tokens.css written; ${report.length} contrast pairs pass.`)
